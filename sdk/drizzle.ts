// `cresslet/drizzle`: Drizzle ORM (drizzle-orm, a peer dependency) on the app's database, and its migrations.
//
//   import { db } from "cresslet";
//   import { drizzle, migrate } from "cresslet/drizzle";
//   import * as schema from "./schema";
//   import migrations from "../drizzle/migrations"; // drizzle-kit generate (driver: "durable-sqlite")
//
//   export const orm = drizzle(db, { schema });     // module top level is fine: it queries only when used
//   await migrate(db, migrations);                  // in the handler, before queries (once per sandbox)
//
// Queries go through db.raw (rows as arrays: a join's `id` columns each keep their value) and orm.batch through
// db.batch (one transaction), so it needs runtime contract 2. Imports nothing from "cresslet" at run time: `db` is
// passed in, so the copy of the SDK the runtime provides is the one used.
import type { DrizzleConfig } from "drizzle-orm";
import { drizzle as proxy, type SqliteRemoteDatabase } from "drizzle-orm/sqlite-proxy";
import type { Database, SQLValue, Statement } from "./index.ts";

type Method = "run" | "all" | "values" | "get";
/** What sqlite-proxy's callbacks answer: `rows` (for `get`, the one row), plus run's changes. */
type Result = { rows: any[] };

class CressletDrizzleError extends Error {
  override name = "CressletError";
}

/** `{ rows }` as sqlite-proxy wants them: arrays of values; for `get`, the first row (or undefined). */
const rowsFor = (method: Method, rows: unknown[]): any => (method === "get" ? rows[0] : rows);

/**
 * Drizzle on the app's database: `drizzle(db, { schema })` with `db` from "cresslet". The usual Drizzle API, with
 * `orm.batch([...])` for several statements in one transaction (all or none). `orm.transaction()` is refused: its
 * BEGIN … COMMIT would span awaits, and other requests' statements would run inside it.
 */
export function drizzle<TSchema extends Record<string, unknown> = Record<string, never>>(
  db: Database,
  config: DrizzleConfig<TSchema> = {},
): SqliteRemoteDatabase<TSchema> {
  if (!db || typeof db.raw !== "function" || typeof db.batch !== "function") {
    throw new CressletDrizzleError('cresslet/drizzle: pass the database: drizzle(db) with `import { db } from "cresslet"` (an SDK with db.raw)');
  }
  const one = async (sql: string, params: unknown[], method: Method): Promise<Result> => {
    const p = params as SQLValue[];
    if (method === "run") return { rows: [], ...(await db.run(sql, ...p)) };
    return { rows: rowsFor(method, await db.raw(sql, ...p)) };
  };
  const many = async (queries: { sql: string; params: unknown[]; method: Method }[]): Promise<Result[]> => {
    const out = await db.batch(queries.map((q): Statement => ({ sql: q.sql, params: q.params as SQLValue[], raw: q.method !== "run" })));
    return out.map((r, i) =>
      queries[i].method === "run"
        ? ({ rows: [], changes: r.changes, lastInsertRowid: r.lastInsertRowid } as Result)
        : { rows: rowsFor(queries[i].method, r.rows) }
    );
  };
  const orm = proxy<TSchema>(one, many, config);
  Object.defineProperty(orm, "transaction", {
    value: () => {
      throw new CressletDrizzleError(
        "cresslet/drizzle: orm.transaction() isn't supported: its statements would span awaits, with other requests' " +
          "statements in between. Use orm.batch([...]): one transaction, all or none.",
      );
    },
  });
  return orm;
}

/** drizzle/migrations.js as `drizzle-kit generate` writes it with `driver: "durable-sqlite"` in drizzle.config.ts. */
export interface Migrations {
  journal: { entries: { idx: number; when: number; tag: string; breakpoints: boolean }[] };
  migrations: Record<string, string>;
}

interface Migration {
  tag: string;
  when: number;
  statements: string[];
  /** It turns foreign keys off around its statements (drizzle-kit's table rebuilds). */
  foreignKeysOff: boolean;
}

/** Drizzle's own table (drizzle-kit and the other migrators read it), plus a unique index for concurrent starts. */
const TABLE = "__drizzle_migrations";
const FOREIGN_KEYS = /^PRAGMA\s+foreign_keys\s*=\s*(\w+)\s*;?$/i;

function parse({ journal, migrations }: Migrations): Migration[] {
  if (!journal || !Array.isArray(journal.entries) || !migrations || typeof migrations !== "object") {
    throw new CressletDrizzleError(
      'cresslet/drizzle: migrate(db, migrations) takes drizzle/migrations.js: `import migrations from "../drizzle/migrations"`, ' +
        'generated by `npx drizzle-kit generate` with `driver: "durable-sqlite"` in drizzle.config.ts',
    );
  }
  return journal.entries.map((e) => {
    const text = migrations[`m${String(e.idx).padStart(4, "0")}`];
    if (typeof text !== "string") throw new CressletDrizzleError(`cresslet/drizzle: migration ${e.tag} is missing from drizzle/migrations.js`);
    if (!e.breakpoints) {
      throw new CressletDrizzleError(
        `cresslet/drizzle: migration ${e.tag} has no statement breakpoints: each statement runs on its own, so set ` +
          "`breakpoints: true` in drizzle.config.ts (the default) and generate it again",
      );
    }
    let foreignKeysOff = false;
    const statements = text.split("--> statement-breakpoint").map((s) => s.trim()).filter((s) => {
      if (!s) return false;
      // PRAGMA can't run inside the migration's transaction (SQLite ignores foreign_keys there): migrate() turns
      // them off around it instead, so a table rebuild's DROP TABLE doesn't cascade.
      const fk = FOREIGN_KEYS.exec(s);
      if (fk) {
        if (/^(off|0|false|no)$/i.test(fk[1])) foreignKeysOff = true;
        return false;
      }
      if (/^PRAGMA\b/i.test(s)) {
        throw new CressletDrizzleError(`cresslet/drizzle: migration ${e.tag}: PRAGMA can't run in a migration (it is one transaction): ${s}`);
      }
      return true;
    });
    return { tag: e.tag, when: Number(e.when), statements, foreignKeysOff };
  });
}

const applied = async (db: Database, when: number) => !!(await db.first(`SELECT 1 FROM ${TABLE} WHERE created_at = ?`, when));

async function apply(db: Database, m: Migration) {
  // The version row first: a request that applied it meanwhile makes this one fail on the unique index, before
  // any of its statements count (the batch is all or none).
  const batch: Statement[] = [{ sql: `INSERT INTO ${TABLE} ("hash", "created_at") VALUES (?, ?)`, params: ["", m.when] }, ...m.statements.map((sql) => ({ sql }))];
  if (!m.foreignKeysOff) return void (await db.batch(batch));
  const on = (await db.first<{ foreign_keys: number }>("PRAGMA foreign_keys"))?.foreign_keys;
  await db.exec("PRAGMA foreign_keys = OFF");
  try {
    await db.batch(batch);
  } finally {
    if (on) await db.exec("PRAGMA foreign_keys = ON");
  }
}

async function run(db: Database, config: Migrations) {
  const list = parse(config);
  await db.exec(
    `CREATE TABLE IF NOT EXISTS ${TABLE} (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at numeric);
     CREATE UNIQUE INDEX IF NOT EXISTS ${TABLE}_created_at ON ${TABLE} (created_at)`,
  );
  // As Drizzle's migrators: the ones newer than the last applied, in order, each in its own transaction.
  const last = Number((await db.first<{ at: number | null }>(`SELECT max(created_at) AS at FROM ${TABLE}`))?.at ?? -Infinity);
  for (const m of list.filter((m) => m.when > last)) {
    try {
      await apply(db, m);
    } catch (e) {
      if (!(await applied(db, m.when))) {
        if (e instanceof Error) e.message = `migration ${m.tag}: ${e.message}`;
        throw e;
      }
      // another request applied it first
    }
  }
}

const done = new WeakMap<Migrations, Promise<void>>();

/**
 * Applies the migrations the database hasn't had (drizzle/migrations.js from `drizzle-kit generate`), each in one
 * transaction (all or none) with its row in `__drizzle_migrations`. Once per sandbox: later calls return the same
 * promise (after a failure, the next call tries again), so call it at the start of every request. Requests starting
 * together apply each migration once.
 */
export function migrate(db: Database, migrations: Migrations): Promise<void> {
  let p = done.get(migrations);
  if (!p) {
    p = run(db, migrations);
    done.set(migrations, p);
    p.catch(() => done.delete(migrations));
  }
  return p;
}
